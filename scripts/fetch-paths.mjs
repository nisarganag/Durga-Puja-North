// Fetches a street-level path for every leg of the route and writes src/data/paths.ts.
// Paths come from the public OpenStreetMap routing service (https://routing.openstreetmap.de),
// so the site can draw them without calling any routing API at runtime.
// Run with: npm run routes
import { writeFileSync } from 'node:fs'
import { STOPS } from '../src/data/route.ts'

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const out = {}

for (let i = 1; i < STOPS.length; i++) {
  const from = STOPS[i - 1]
  const to = STOPS[i]
  if (!from.place || !to.place) continue

  const byCab = to.leg?.steps.some((s) => s.modes.includes('cab'))
  const profile = byCab ? 'car' : 'foot'
  const coords = `${from.place.lng},${from.place.lat};${to.place.lng},${to.place.lat}`
  const url = `https://routing.openstreetmap.de/routed-${profile}/route/v1/driving/${coords}?overview=full&geometries=polyline`

  const res = await fetch(url, { headers: { 'User-Agent': 'durga-puja-north route guide (personal project)' } })
  if (!res.ok) throw new Error(`${from.id} → ${to.id}: HTTP ${res.status}`)
  const data = await res.json()
  if (data.code !== 'Ok') throw new Error(`${from.id} → ${to.id}: ${data.code}`)

  const route = data.routes[0]
  out[to.id] = { polyline: route.geometry, meters: Math.round(route.distance) }
  console.log(`${from.id.padEnd(12)} → ${to.id.padEnd(12)} ${profile.padEnd(4)} ${String(Math.round(route.distance)).padStart(5)} m`)
  await sleep(400)
}

const file = `// Generated by scripts/fetch-paths.mjs. Do not edit by hand.
// Street paths © OpenStreetMap contributors (ODbL), routed by routing.openstreetmap.de.
// Keyed by the stop each path leads to. Polylines use Google's encoded format, precision 5.

export const PATHS: Record<string, { polyline: string; meters: number }> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(new URL('../src/data/paths.ts', import.meta.url), file)
console.log(`\nWrote ${Object.keys(out).length} paths to src/data/paths.ts`)
